   private static BlockSoundCollection<Optional<Holder<SoundEvent>>> registerForBlockSoundSetWithFallback(final ResourceKey<BlockSoundSet> blockSoundSet, final BlockSoundCollection<Boolean> mask, final BlockSoundCollection<Optional<Holder<SoundEvent>>> fallback) {
      BlockSoundCollection<Optional<Holder<SoundEvent>>> original = registerForBlockSoundSet(blockSoundSet, mask);
      return BlockSoundCollection.zipMap(original, fallback, (o, f) -> o.isPresent() ? o : f);
   }

